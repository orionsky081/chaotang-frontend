/**
 * 守门心跳（2026-07-18 立）。
 *
 * 守门测试最阴的死法不是报错，是**扫描面悄悄塌成 0，然后它永远绿着**——
 * 正则被改坏、目录被重命名、过滤条件写反，都会让"遍历 + 断言无命中"退化成
 * "遍历了个空集 + 断言当然无命中"。没有任何错误信息，绿灯本身就是伪装，
 * 而所有人都以为有人看着。
 *
 * 这个模块把"证明机制还活着"这件事从**注释**挪进**函数签名**：
 * 你想用心跳，就必须交出扫描计数；交不出来，就写不出这行调用。
 * 下一个写守门的人不会读注释，但他绕不过一个必填参数。
 *
 * ⚠️ 但签名只能约束**用了它的人**。有人新写一条守门、干脆不调用它，签名管不着——
 * 那一层由 `scripts/harness-refs.nodetest.ts` 的「每条守门都必须有心跳」元断言对账
 * （拿 package.json 的 `test:guards` 名单去点名）。两层合起来才闭环。
 */

import assert from 'node:assert/strict';

/**
 * 断言扫描面非空，并打印一行自曝。
 *
 * @param name   守门名，出现在自曝行和失败信息里。
 * @param counts **证明机制跑过**的计数，如 `{ 文件: 137, 引用: 72 }`。
 *               每一项都必须 > 0 —— 传进来的每个数字都是一句"我确实看了这么多东西"。
 *
 *               只传**扫描面**，不要传**发现数**：`missing: 0` 是好事（没问题），
 *               而 `扫描文件: 0` 是坏事（没在看）。把后者混进来会让守门在健康时报红，
 *               两周内就会被人加 skip 绕过去。
 *
 * 数字大小本身不判红：137→132 是正常漂移（有人删了个脚本），
 * 为漂移红一次只会训练大家学会无视这个守门。只有归零才是心跳停止。
 */
export function assertScanAlive(name: string, counts: Record<string, number>): void {
  const entries = Object.entries(counts);

  assert.ok(
    entries.length > 0,
    `[${name}] assertScanAlive 收到空的 counts —— 心跳检测自己没了心跳。` +
      `请传入证明扫描跑过的计数，如 { 文件: files.length }。`,
  );

  console.log(
    `\n  📊 ${name} 扫描面：${entries.map(([k, v]) => `${k} ${v}`).join(' · ')}` +
      `\n     数字突然缩水(尤其归零)= 正则或目录结构变了，这个守门可能已经名存实亡。\n`,
  );

  for (const [key, value] of entries) {
    assert.ok(
      value > 0,
      `[${name}] 扫描面「${key}」= 0 —— 这个守门已经死了，却还在发绿灯。\n` +
        `  它的其余断言此刻会"无事发生"地全部通过，因为它们遍历的是空集。\n` +
        `  去查：遍历的目录还在吗？扩展名/正则过滤是否被改坏？`,
    );
  }
}
